function setup({fail=false,map=false}={}) {
  const dom=new JSDOM(read('observatorio-satelital/index.html'),{url:'https://hidrogenoverdeturquesa.com/observatorio-satelital/',runScripts:'outside-only'});
  const w=dom.window,d=w.document,state={fail,requests:[],point:null,query:0,layers:new Set(),groups:[],satellite:false};
  w.fetch=async url=>{state.requests.push(url);if(state.fail)throw new Error('Offline');return {ok:true,json:async()=>JSON.parse(read(url.split('?')[0].slice(1)))};};
  const m={removeLayer(layer){state.layers.delete(layer);},fitBounds(bounds){state.bounds=bounds;},invalidateSize(){state.resized=true;}};
  w.HVTObservatory={map:map?m:null,selectPoint(lat,lon,name){state.point={lat,lon,name};d.dispatchEvent(new w.CustomEvent('hvt:point-selected'));},queryPower(){state.query++;},setSatellite(value){state.satellite=value;}};
  if(map)w.L={geoJSON(collection,options){
    const layers=collection.features.map(feature=>{const layer={feature,events:{},setStyle(style){this.style=style;},bindTooltip(tip){this.tip=tip;},on(name,fn){this.events[name]=fn;},getBounds(){return feature.properties.code;},bringToFront(){this.front=true;}};options.onEachFeature(feature,layer);layer.style=options.style(feature);return layer;});
    const group={layers,options,addTo(){state.layers.add(this);return this;},eachLayer(fn){layers.forEach(fn);},getBounds(){return 'boyaca';}};state.groups.push(group);return group;
  }};
  w.eval(read('js/observatorio-organicos.js'));
  return {w,d,state,change(id,value,event='change'){d.getElementById(id).value=value;d.getElementById(id).dispatchEvent(new w.Event(event));},close(){w.close();}};
}
test('official municipal join covers 123 municipalities with traceable, distinct evidence',()=>{
  const records=core.validate(data,geo,catalog);
  assert.equal(records.filter(r=>r.context).length,87);
  assert.equal(records.filter(r=>r.organic).length,2);
  assert.equal(records.filter(r=>r.activities.length).length,20);
  assert.ok(records.every(r=>r.code.startsWith('15')));
  const tunja=records.find(r=>r.code==='15001'),paipa=records.find(r=>r.code==='15516');
  assert.equal(tunja.organic.value,39);assert.equal(tunja.organic.year,2024);assert.equal(tunja.organic.page,23);
  assert.equal(paipa.organic.value,33.8);assert.match(paipa.organic.scope,/disposición final/);assert.match(paipa.organic.qualityNote,/inconsistencia/);
  assert.ok(records.every(r=>r.activities.every(a=>a.quantityTon===null && a.page>0 && a.dateLabel)));
  assert.ok(records.filter(r=>r.context).every(r=>r.context.period===null));
  assert.ok(Object.values(catalog.sources).every(s=>/^[a-f0-9]{64}$/.test(s.sha256)));
  const broken=structuredClone(geo);broken.features[0].properties.code=broken.features[1].properties.code;
  assert.throws(()=>core.validate(data,broken,catalog),/Códigos/);
  const bad=structuredClone(data);bad.municipalities.find(r=>r.organic).organic.value=null;
  assert.throws(()=>core.validate(bad,geo,catalog),/Caracterización/);
});
test('search tolerates accents and CSV leaves missing organic quantities blank',()=>{
  assert.equal(core.filterRecords(data.municipalities,'sogamoso','all')[0].code,'15759');
  assert.equal(core.filterRecords(data.municipalities,'15001','characterization')[0].name,'Tunja');
  assert.equal(core.filterRecords(data.municipalities,'Chiquinquira','all')[0].code,'15176');
  assert.equal(core.filterRecords(data.municipalities,'Tunja','missing').length,0);
  const missing=data.municipalities.find(r=>r.status==='missing');
  const csv=core.toCSV([missing],catalog.sources);
  assert.ok(csv.includes('"Sin dato integrado","","","","",""'));
  assert.match(csv,/NO_organicos/);assert.match(csv,/Sin dato no significa cero/);
  const rows=core.toCSV(data.municipalities,catalog.sources).split('\r\n');assert.equal(rows.length,124);
  assert.match(core.toCSV([{...missing,name:'=FORMULA()'}],catalog.sources),/'=FORMULA/);
});
